/* Scene playback is independent of benchmark data and chart rendering. */
(() => {
'use strict';
// Videos load only when played and stop when offscreen or the tab is hidden.
function observeVideo(video, autoplay = false) {
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
  let visible = false;
  let wantsPlayback = autoplay && !reducedMotion.matches && !navigator.connection?.saveData;
  if (autoplay) {
    video.defaultMuted = true;
    video.muted = true;
    video.playsInline = true;
    video.autoplay = wantsPlayback;
    if (!wantsPlayback) video.pause();
  }
  let internalPause = false;
  function playVisible() {
    if (visible && !document.hidden && wantsPlayback) video.play().catch(() => {});
  }
  function suspend() {
    if (!video.paused) { internalPause = true; video.pause(); }
  }
  video.addEventListener('play', () => {
    wantsPlayback = true;
    if (!visible || document.hidden) suspend();
  });
  video.addEventListener('pause', () => {
    if (internalPause) internalPause = false;
    else wantsPlayback = false;
  });
  video.addEventListener('loadeddata', playVisible);
  video.addEventListener('canplay', playVisible);
  new IntersectionObserver(entries => {
    visible = entries[0].isIntersecting;
    if (visible) playVisible(); else suspend();
  }, { threshold: .15 }).observe(video);
  document.addEventListener('visibilitychange', () => {
    if (document.hidden) suspend(); else playVisible();
  });
  reducedMotion.addEventListener('change', () => {
    if (reducedMotion.matches) { video.autoplay = false; wantsPlayback = false; suspend(); }
  });
  return {
    select(src, poster, label) {
      suspend();
      video.poster = poster;
      video.querySelector('source').src = src;
      video.querySelector('a').href = src;
      video.querySelector('a').textContent = 'Download this video.';
      video.setAttribute('aria-label', label);
      video.load();
      wantsPlayback = true;
      playVisible();
    }
  };
}

const sceneVideo = document.querySelector('#scene-video');
const roomPlayer = observeVideo(sceneVideo, true);
const sceneExplorer = document.querySelector('#scene-explorer');
const sceneHighlights = {
  office: { name: 'Office', duration: 20, source: "Original photo taken in Chuanxia Zheng’s office" },
  laboratory: { name: 'Laboratory', duration: 20, source: 'Original image generated by ChatGPT Images 2.5, motivated by Mengdi Wang' },
  kitchen: { name: 'Kitchen', duration: 21, source: "Original photo taken in Jianfei Yang’s lab" }
};
function updateSceneCaption(scene) {
  const caption = document.querySelector('#scene-video-caption');
  caption.textContent = `${scene.name} · ${scene.source}`;
}
let activeScene = 'office';
updateSceneCaption(sceneHighlights[activeScene]);
function syncExplorerRoom() {
  document.querySelector(`[data-teaser-room="${activeScene}"]`)?.click();
}
document.querySelectorAll('[data-scene-video]').forEach(button => {
  button.addEventListener('click', () => {
    const key = button.dataset.sceneVideo;
    if (key === activeScene) return;
    activeScene = key;
    const scene = sceneHighlights[key];
    document.querySelectorAll('[data-scene-video]').forEach(item => item.setAttribute('aria-pressed', String(item === button)));
    roomPlayer.select(`assets/scenes/${key}.mp4`, `assets/scenes/${key}.webp`, `Generated ${scene.name.toLowerCase()}: ${scene.duration}-second highlight`);
    updateSceneCaption(scene);
    syncExplorerRoom();
  });
});
document.querySelector('#explore-scene').addEventListener('click', event => {
  event.preventDefault();
  syncExplorerRoom();
  requestAnimationFrame(() => {
    sceneExplorer.focus({ preventScroll: true });
    sceneExplorer.scrollIntoView({ block: 'start', behavior: 'instant' });
  });
});

})();
